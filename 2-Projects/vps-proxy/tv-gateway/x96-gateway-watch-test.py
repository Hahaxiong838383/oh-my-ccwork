#!/usr/bin/env python3
"""Run the real gateway watcher with an offline Android command and clock fixture."""
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile

PRIMARY = "192.168.1.19"
STANDBY = "192.168.1.254"
BOOT = "11111111-2222-3333-4444-555555555555"
HERE = Path(__file__).resolve().parent


def simulate(command, args):
    fixture = Path(os.environ["X96_WATCH_FIXTURE"])
    schedule = json.loads((fixture / "schedule").read_text())
    cursor = fixture / "step"
    step = int(cursor.read_text())
    row = schedule[step]
    mode = row["playback"]
    receipt = fixture / "receipt"

    if command == "getprop" and args == ["sys.boot_completed"]:
        print(int(row["ready"]))
    elif command == "ip" and args == ["-4", "addr", "show", "dev", "eth0"]:
        print("    inet 192.168.1.144/24 scope global eth0")
    elif command == "route" and len(args) == 2:
        if args[0] == "check":
            return int(receipt.read_text().split()[1] != args[1])
        if args[0] == "apply" and args[1] in (PRIMARY, STANDBY):
            with (fixture / "applied").open("a") as out:
                print(step + 1, args[1], file=out)
            receipt.write_text(f"{BOOT} {args[1]}\n")
        else:
            raise ValueError(args)
    elif command == "x96-gw-probe":
        with (fixture / "probes").open("a") as out:
            print(step + 1, args[0], file=out)
        return int(not row[{PRIMARY: "primary", STANDBY: "standby"}[args[0]]])
    elif command == "dumpsys":
        if args == ["activity", "activities"]:
            package = "com.player.diyp2020" if mode.startswith("diyp") else "org.smarttube.beta"
            (fixture / "vdec").write_text("No vdec.\n" if mode == "idle" else "frame count : 88\n")
            print(f"mResumedActivity: ActivityRecord{{123 u0 {package}/.Playback}}")
        elif args == ["media_session"]:
            print("Sessions Stack - have 1 session")
            print("state=PlaybackState {state=" + ("2," if mode == "idle" else "3,"))
        else:
            raise ValueError(args)
    elif command == "ss" and args == ["-tnip"]:
        sequence = fixture / "ss_count"
        count = int(sequence.read_text()) + 1
        sequence.write_text(str(count))
        remote = "203.0.113.1:443" if mode == "diyp-external" else "192.168.1.211:4022"
        port = 43300 + (count if mode == "diyp-reconnected" else 0)
        rx = 20000 + (0 if mode == "diyp-stalled" else count * 8192)
        print(f'ESTAB 0 0 192.168.1.144:{port} {remote} users:(("player.diyp2020",pid=123,fd=5))')
        print(f"    cubic wscale:7,7 bytes_received:{rx} segs_in:20")
    elif command == "sleep" and args == ["1"]:
        pass  # The second ss sample is generated by the same socket fixture.
    elif command == "sleep" and args in (["5"], ["10"]):
        if step + 1 == len(schedule):
            (fixture / "finished").touch()
            os.kill(os.getppid(), signal.SIGTERM)
        else:
            cursor.write_text(str(step + 1))
    elif command == "log":
        with (fixture / "log").open("a") as out:
            print(*args, file=out)
    else:
        raise ValueError((command, args))
    return 0


def sample(primary=True, standby=True, playback="idle", ready=True):
    return dict(primary=primary, standby=standby, playback=playback, ready=ready)


def scenario(name, active, rows, expected, expected_probes=()):
    with tempfile.TemporaryDirectory() as folder:
        fixture = Path(folder)
        binaries = fixture / "bin"
        binaries.mkdir()
        original = (HERE / "x96-gateway-watch.sh").read_text()
        # Only filesystem paths change. Branches, probe thresholds, awk, grep and flock stay real.
        for before, after in [("/system/bin/sh", "/bin/sh"), ("/data/adb/dsh-gateway", folder),
                              ("/data/misc/x96-boot-status/gateway", str(fixture / "receipt")),
                              ("/proc/sys/kernel/random/boot_id", str(fixture / "boot")),
                              ("/sys/class/net/eth0/carrier", str(fixture / "carrier")),
                              ("/sys/class/vdec/vdec_status", str(fixture / "vdec"))]:
            assert before in original, before
            original = original.replace(before, after)
        watcher = fixture / "watch.sh"
        watcher.write_text(original)
        dispatcher = binaries / "dispatcher"
        dispatcher.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{Path(__file__).resolve()}" --stub "${{0##*/}}" "$@"\n')
        dispatcher.chmod(0o700)
        for cmd in ["ip", "sleep", "ss", "log", "getprop", "dumpsys", "route"]:
            (binaries / cmd).symlink_to(dispatcher)
        (fixture / "x96-gw-probe").symlink_to(dispatcher)
        (fixture / "x96-gateway-route.sh").write_text('#!/bin/sh\nexec route "$@"\n')
        for key, value in {"schedule": json.dumps(rows), "receipt": f"{BOOT} {active}\n",
                           "boot": BOOT, "carrier": "1", "step": "0", "ss_count": "0",
                           "applied": "", "probes": "", "vdec": "No vdec.\n"}.items():
            (fixture / key).write_text(value)
        env = dict(os.environ, PATH=str(binaries) + ":" + os.environ["PATH"], X96_WATCH_FIXTURE=folder)
        result = subprocess.run(["/bin/sh", watcher], env=env, capture_output=True, text=True, timeout=15)
        assert (fixture / "finished").exists() and result.returncode == -signal.SIGTERM, (name, result.stderr)
        assert not result.stderr, (name, result.stderr)
        applied = (fixture / "applied").read_text().splitlines()
        assert applied == [f"{tick} {gw}" for tick, gw in expected], (name, applied)
        probes = (fixture / "probes").read_text().splitlines()
        assert all(f"{tick} {gw}" in probes for tick, gw in expected_probes), (name, probes)
        assert len(probes) >= sum(r["ready"] for r in rows), (name, "watcher did not run")
        print("PASS", name)


def main():
    ok, down, both_down = sample(), sample(primary=False), sample(False, False)
    scenario("isolated failures stay primary", PRIMARY, [down, ok, down, ok], [])
    scenario("consecutive failures switch once", PRIMARY, [ok, down, down, down], [(3, STANDBY)], [(3, STANDBY)])
    scenario("neither gateway healthy stays primary", PRIMARY, [both_down]*4, [], [(2, STANDBY)])
    scenario("incomplete boot resets the streak", PRIMARY, [down, sample(ready=False), down, ok], [])
    scenario("three consecutive primary successes return", STANDBY, [ok, ok, down, ok, ok, ok], [(6, PRIMARY)])
    external = sample(playback="external")
    scenario("external stream holds healthy standby", STANDBY, [external]*4, [], [(3, STANDBY)])
    scenario("idle releases held return", STANDBY, [external]*4+[ok], [(5, PRIMARY)])
    scenario("failed standby returns during external playback", STANDBY,
             [external]*3+[sample(standby=False, playback="external")], [(4, PRIMARY)], [(4, STANDBY)])
    scenario("flowing LAN DIYP stream permits return", STANDBY, [sample(playback="diyp-lan")]*3, [(3, PRIMARY)])
    for mode in ("diyp-stalled", "diyp-reconnected", "diyp-external"):
        scenario(mode + " stream holds standby", STANDBY, [sample(playback=mode)]*3, [], [(3, STANDBY)])


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--stub":
        sys.exit(simulate(sys.argv[2], sys.argv[3:]))
    main()

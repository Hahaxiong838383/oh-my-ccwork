function includesAny(text: string, words: string[]): boolean {
  for (const w of words) {
    if (text.includes(w)) return true;
  }
  return false;
}

/** 仅供测试 / 监控：本轮是否命中 AI 话题（决定门控注入）。 */
export function matchesAiTopic(text: string): boolean {
  if (!text) return false;
  return includesAny(text, AI_KEYWORDS) || includesAny(text, PHONETIC_ALIASES) || includesAny(text, DANGER_KEYWORDS);
}


// 记忆安全兜底过滤（临时）
// ⚠️ 这是【简单的关键词兜底】，不是完整的儿童安全防护规则。
//    科学的安全规则（实时识别 + 分级干预 + 家长/人工通道）由产品设计后替换/叠加，见后续立项。
// 目的：自杀 / 自残 / 自我伤害 / 极端家庭压力等危机信号，绝不写入记忆系统——
//       避免被当作"记忆"注入后续对话上下文而强化伤害。
// 策略：命中即拦截。宁可误伤少数边界内容（如"想阻止朋友自残"），安全优先。

const CRISIS_PATTERN =
  /自杀|自尽|轻生|自残|自伤|割腕|割手|跳楼|跳河|上吊|去死|想死|不想活|活不下去|别活了|死了算了|死了好了|了结生命|结束生命|别回家/;

/** 危机内容判定：命中则该条记忆不入库。text 为记忆条目的 content。 */
export function isCrisisContent(text: string): boolean {
  return CRISIS_PATTERN.test(text ?? '');
}

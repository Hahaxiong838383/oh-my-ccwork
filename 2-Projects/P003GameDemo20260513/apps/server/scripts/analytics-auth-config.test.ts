import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { SignJWT } from 'jose';
const dir = mkdtempSync(join(tmpdir(), 'analytics-auth-'));
process.env.CONFIG_DB_PATH = join(dir, 'config.db');
const { configStore, CONFIG_KEYS, invalidValueMessage } = await import('../src/config-store.js');
assert.equal(CONFIG_KEYS['analytics.event_upload_enabled']?.builtinDefault, false, '上传开关必须注册且默认关闭');
assert.equal(CONFIG_KEYS['analytics.daily_upload_hour_cst'].builtinDefault, 23);
assert.match(invalidValueMessage('analytics.daily_upload_hour_cst'), /小时/);
const SN = 'FAKE-DEVICE';
assert.equal((configStore.effectiveSnapshot(SN).analytics as any).event_upload_enabled,false);
assert.equal((configStore.effectiveSnapshot(SN).analytics as any).daily_upload_hour_cst,23);
assert.equal((configStore.effectiveSnapshot(SN).analytics as any).request_gzip_enabled,false);
const rev1 = configStore.setGlobal('analytics.event_upload_enabled', true)!;
const rev2 = configStore.setValue(SN, 'analytics.event_upload_enabled', false)!;
assert.ok(rev2 > rev1);
assert.equal((configStore.effectiveSnapshot(SN).analytics as any).event_upload_enabled, false);
assert.ok(configStore.clearForSn(SN, 'analytics.event_upload_enabled')! > rev2);
assert.equal((configStore.effectiveSnapshot(SN).analytics as any).event_upload_enabled, true);
for (const hour of [0, 23]) assert.ok(configStore.setGlobal('analytics.daily_upload_hour_cst', hour));
for (const hour of [-1, 24, 0.5, '0']) assert.equal(configStore.setGlobal('analytics.daily_upload_hour_cst', hour), null);
const { verifyDeviceCredential } = await import('../src/device-credential.js');
const { AnalyticsDeviceReader } = await import('../src/analytics/device-context.js');
const registry = join(dir, 'devices.db');
const db = new DatabaseSync(registry);
db.exec(`PRAGMA journal_mode=WAL; CREATE TABLE device_registry(sn TEXT PRIMARY KEY,status TEXT,binding_policy TEXT DEFAULT 'legacy',binding_version INTEGER DEFAULT 0,parent_account_id TEXT); CREATE TABLE device_binding_state(sn TEXT PRIMARY KEY,binding_policy TEXT,binding_version INTEGER); CREATE TABLE device_credential_revocation(sn TEXT PRIMARY KEY,not_before_sec INTEGER); INSERT INTO device_registry(sn,status) VALUES ('FAKE-DEVICE','active'),('DISABLED','disabled'); INSERT INTO device_credential_revocation VALUES('FAKE-DEVICE',100);`);
const reader = new AnalyticsDeviceReader({ devicesPath: registry, configPath: process.env.CONFIG_DB_PATH!, deviceKeySecret: 'fake-stable-key-secret', envAllow: ['ENV-ONLY','DISABLED'] });
const sign = (iat:number) => new SignJWT({kind:'p003-device'}).setSubject(SN).setProtectedHeader({alg:'HS256'}).setIssuedAt(iat).setExpirationTime('1h').sign(new TextEncoder().encode('fake-jwt-secret'));
assert.equal(await verifyDeviceCredential('Bearer '+await sign(100), 'fake-jwt-secret', reader.acceptsCredential.bind(reader),reader.readCredentialState.bind(reader)), null);
assert.deepEqual(await verifyDeviceCredential('Bearer '+await sign(101), 'fake-jwt-secret', reader.acceptsCredential.bind(reader),reader.readCredentialState.bind(reader)), {sn:SN});
assert.equal(await verifyDeviceCredential('bad', 'fake-jwt-secret'), null);
assert.equal(await verifyDeviceCredential('Bearer '+await sign(101), 'wrong'), null);
const ctx = reader.readAnalyticsDeviceContext(SN);
assert.equal(ctx.active,true); assert.equal(ctx.uploadEnabled,true); assert.equal(ctx.uploadHourCst,23);
assert.equal(ctx.deviceKey,reader.readAnalyticsDeviceContext(SN).deviceKey);
assert.ok(!ctx.deviceKey.includes(SN));
assert.equal(reader.readAnalyticsDeviceContext('ENV-ONLY').active,true);
assert.equal(reader.readAnalyticsDeviceContext('DISABLED').active,false);
assert.equal(reader.readAnalyticsDeviceContext('OUT').active,false);
// Live WAL updates must become visible without restarting the isolated service.
db.prepare('UPDATE device_registry SET status=? WHERE sn=?').run('disabled',SN);
assert.equal(reader.readAnalyticsDeviceContext(SN).active,false);
const unavailable = new AnalyticsDeviceReader({devicesPath:join(dir,'missing.db'),configPath:process.env.CONFIG_DB_PATH!,deviceKeySecret:'fake',envAllow:[SN]});
await assert.rejects(verifyDeviceCredential('Bearer '+await sign(101),'fake-jwt-secret',unavailable.acceptsCredential.bind(unavailable),unavailable.readCredentialState.bind(unavailable)), /ANALYTICS_DEPENDENCY_UNAVAILABLE/);
assert.throws(()=>unavailable.readAnalyticsDeviceContext(SN), /ANALYTICS_DEPENDENCY_UNAVAILABLE/);
assert.throws(()=>new AnalyticsDeviceReader({devicesPath:'relative.db',configPath:process.env.CONFIG_DB_PATH!,deviceKeySecret:'fake',envAllow:[]}),/absolute/);
db.close(); rmSync(dir,{recursive:true,force:true});
console.log('analytics auth/config: PASS (revocation, WAL visibility, active/env, config boundaries, dependency failure)');

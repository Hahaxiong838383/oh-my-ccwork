import assert from 'node:assert/strict';
import { mkdtempSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { readBleCredentialStatuses } from '../src/admin-device-credential-status.js';

const tmp = mkdtempSync(join(tmpdir(), 'p003-admin-credential-'));
process.chdir(tmp);
for (const n of ['DEVICES','ACCOUNTS','PROFILE','PAIRING','CONFIG','SMS','TELEMETRY','MEMORY','LOCAL_AUDIO']) process.env[n+'_DB_PATH'] = join(tmp,n+'.db');
Object.assign(process.env,{AUTH_JWT_SECRET:'isolated-admin-credential-display-secret-32-bytes',STUDIO_USER:'test-admin',STUDIO_PASS:'test-pass',LOCAL_AUDIO_GENERATION_PAUSED:'1'});
const { deviceRegistryStore: registry } = await import('../src/device-registry-store.js');
const { getBleBindingStore } = await import('../src/ble-binding-store.js');
getBleBindingStore();
const { adminDataRoute, credentialView } = await import('../src/routes/admin-data.js');
const { authRoute } = await import('../src/routes/auth.js');
const { Hono } = await import('hono');
const db = new DatabaseSync(process.env.DEVICES_DB_PATH!);
const sn = 'BJP00326110900000031';
registry.add(sn, 'isolated fixture');
db.prepare("UPDATE device_registry SET binding_policy='ble-key-v1',parent_account_id='acct-A',binding_version=1 WHERE sn=?").run(sn);
const device = () => registry.list().find(d => d.sn===sn)!;
const now = 1800000000000;
let n = 0;
const pass = (s: string) => console.log(`PASS ${++n} ${s}`);
const get = (at=now) => readBleCredentialStatuses([device()],at).get(sn)!;
const receipt = (id: string, bound: number, claimed: number|null, activated: number|null, revoked: number|null, account='acct-A', version=1) => {
  db.prepare(`INSERT INTO ble_binding_receipt(binding_id,challenge_id,sn,account_id,device_key_id,binding_version,nonce_hash,credential_pk,public_id,bound_at_ms,claim_expires_at_ms,claimed_at_ms,activated_at_ms,revoked_at_ms)
    VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)`).run(id,id,sn,account,'key',version,id,'public-only-fixture','dev-fixture',bound,bound+600000,claimed,activated,revoked);
};
assert.equal(get().pairing?.state,'none'); assert.equal(get().issued_at_ms,null); pass('empty receipt is no record');
receipt('old',now-3600000,now-3500000,now-3499000,now-1000000);
receipt('new',now-1000000,null,null,null);
assert.equal(get().issued_at_ms,now-3500000); assert.equal(get().authenticated_at_ms,now-3499000);
assert.equal(get().pairing?.state,'claim_expired'); assert.equal(get().pairing?.claimed_at_ms,null);
assert.equal(credentialView(device()).credential_expires_at,null); pass('C regression: historical BLE claim recognized separately from latest unclaimed pairing; legacy field unchanged');
assert.equal(get(now-400001).pairing?.state,'waiting_claim'); assert.equal(get(now-400000).pairing?.state,'claim_expired'); pass('claim deadline exact boundary, never used as JWT expiry');
db.prepare("UPDATE ble_binding_receipt SET claimed_at_ms=? WHERE binding_id='new'").run(now-900000);
assert.equal(get().pairing?.state,'waiting_auth'); pass('claimed but not authenticated, even beyond claim window');
db.prepare("UPDATE ble_binding_receipt SET activated_at_ms=? WHERE binding_id='new'").run(now-800000);
assert.equal(get().pairing?.state,'authenticated'); pass('only recorded real authentication completes this pairing');
db.prepare("UPDATE ble_binding_receipt SET revoked_at_ms=? WHERE binding_id='new'").run(now-700000);
assert.equal(get().pairing?.state,'revoked'); pass('revoked latest receipt is not shown active');
const stale = device();
db.prepare("UPDATE device_registry SET parent_account_id='acct-B',binding_version=2 WHERE sn=?").run(sn);
assert.equal(get().issued_at_ms,null); assert.equal(get().pairing?.state,'none');
assert.equal(readBleCredentialStatuses([stale],now).get(sn)?.state,'unavailable'); pass('owner/generation and concurrent rebind isolation');
receipt('wrong-owner',now-100,now-90,now-80,null,'acct-A',2);
receipt('wrong-version',now-70,now-60,now-50,null,'acct-B',1);
assert.equal(get().issued_at_ms,null); assert.equal(get().authenticated_at_ms,null); pass('neither owner-only nor version-only matches leak history');
db.prepare("UPDATE device_registry SET parent_account_id='acct-A',binding_version=1 WHERE sn=?").run(sn);
const snapshot = () => JSON.stringify({registry:db.prepare('SELECT * FROM device_registry').all(),receipts:db.prepare('SELECT * FROM ble_binding_receipt').all(),revocations:db.prepare('SELECT * FROM device_credential_revocation').all()});
const before = snapshot(); for(let i=0;i<20;i++) get(); assert.equal(snapshot(),before); pass('repeated read-only queries change no registry/receipt/revocation rows');
const missing = join(tmp,'absent.db');
assert.equal(readBleCredentialStatuses([device()],now,missing).get(sn)?.state,'unavailable'); assert.equal(existsSync(missing),false); pass('missing DB degrades honestly and is never created');
const oldDb = join(tmp,'old.db'); new DatabaseSync(oldDb).close();
assert.equal(readBleCredentialStatuses([device()],now,oldDb).get(sn)?.state,'unavailable'); pass('missing table degrades to unavailable, never unissued');
assert.equal(readBleCredentialStatuses([{...device(),binding_policy:'legacy'}],now,missing).size,0); assert.equal(existsSync(missing),false); pass('legacy does not open the new reader');

const app = new Hono(); app.route('/api/auth',authRoute); app.route('/api/admin',adminDataRoute);
// Registry triggers keep generations monotonic across the earlier simulated rebind.
receipt('http',now-500000,now-450000,now-440000,null,'acct-A',device().binding_version);
assert.equal((await app.request('/api/admin/devices')).status,401);
const login = await app.request('/api/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'test-admin',password:'test-pass'})});
assert.equal(login.status,200); const token=(await login.json() as any).token;
const request=()=>app.request('/api/admin/devices',{headers:{authorization:'Bearer '+token}});
const httpBefore = snapshot(); const response = await request(); assert.equal(response.status,200);
const body=await response.json() as any; const row=body.devices.find((d:any)=>d.sn===sn);
assert.equal(row.ble_status.issued_at_ms,now-450000); assert.equal(row.ble_status.pairing.state,'authenticated');
assert.equal(row.credential_expires_at,null); assert.equal(snapshot(),httpBefore);
assert.ok(!JSON.stringify(body).includes(token)); assert.ok(!JSON.stringify(row.ble_status).includes('public-only-fixture')); pass('real authenticated admin GET adds evidence only; no secrets or writes');
registry.add('BJP00326110900000032','legacy');registry.recordCredential('BJP00326110900000032',now-1000,now+86400000);
const legacy=(await (await request()).json() as any).devices.find((d:any)=>d.sn.endsWith('00000032'));
assert.equal(legacy.ble_status,null); assert.equal(legacy.credential_expires_at,now+86400000); assert.equal(legacy.credential_source,'registry'); pass('legacy admin response fields retain exact values');
const guestLogin=await app.request('/api/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'guest',password:'123456'})});
const guest=(await guestLogin.json() as any).token;
assert.equal((await app.request('/api/admin/devices',{headers:{authorization:'Bearer '+guest}})).status,403);
const issue=await app.request('/api/admin/devices/'+sn+'/credential',{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:JSON.stringify({days:30})});
assert.equal(issue.status,403);assert.equal((await issue.json() as any).error,'device_proof_required');pass('guest gate and BLE manual issuance restriction unchanged');
db.close();console.log(`PASS ${n}/${n} admin credential status checks`);

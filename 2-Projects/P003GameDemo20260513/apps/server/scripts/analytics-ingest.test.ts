import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const { AnalyticsStore }=await import('../src/analytics/store.js');
const {validateAnalyticsBatch}=await import('../src/analytics/contracts.js');
const {settleAnalyticsBatch}=await import('../src/analytics/ingest.js');
const dir=mkdtempSync(join(tmpdir(),'analytics-ingest-'));
const store=new AnalyticsStore(join(dir,'analytics.db'));
const event=(id:string, extra={})=>({schema_version:1,client_event_id:id,event_name:'app.session_started',occurred_at_ms:Date.now(),session_id:'session-1',sequence:1,priority:'normal',context:{},properties:{platform:'Android',entry_mode:'launcher'},...extra});
const batch=(events:any[],id='batch-1')=>validateAnalyticsBatch({schema_version:1,batch_id:id,sent_at_ms:Date.now(),client:{product:'p003',component:'godot',protocol_version:'1.0',content_version:'v321'},events});
const ctx={deviceKey:'fake-device-key',active:true,uploadEnabled:true,uploadHourCst:23};
const A=event('A'), B=event('B');
const run=(events:any[],key='request-1',context=ctx)=>settleAnalyticsBatch(store,context,batch(events),key);
let ack=run([A,A,B]); assert.deepEqual(ack.accepted_event_ids,['A','B']); assert.deepEqual(ack.duplicated_event_ids,[]);
ack=run([A,B]);assert.deepEqual(ack.duplicated_event_ids,['A','B']);
ack=run([{...A,sequence:2}]);assert.deepEqual(ack.rejected,[{client_event_id:'A',reason:'client_event_id_conflict'}]);
ack=run([event('C'),event('C',{sequence:2})]);assert.deepEqual(ack.rejected,[{client_event_id:'C',reason:'client_event_id_conflict'}]);
assert.deepEqual(run([A],'request-1',{...ctx,deviceKey:'another'}).accepted_event_ids,['A']);
ack=run([event('D'),event('E',{event_name:'unregistered.event'}),event('F',{properties:{child_name:'secret-rejected-text'}})]);
assert.deepEqual(ack.accepted_event_ids,['D']);assert.deepEqual(ack.rejected,[{client_event_id:'E',reason:'event_not_allowed'},{client_event_id:'F',reason:'invalid_properties'}]);
assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM analytics_batch WHERE request_id=?').get('request-1')!.n,6);
assert.equal(JSON.stringify(store.db.prepare('SELECT * FROM analytics_settlement').all()).includes('secret-rejected-text'),false);
store.db.exec(`CREATE TRIGGER fail_insert BEFORE INSERT ON analytics_event WHEN NEW.client_event_id='FAIL' BEGIN SELECT RAISE(ABORT,'test'); END;`);
assert.throws(()=>run([event('WONT_COMMIT'),event('FAIL')]),/ANALYTICS_STORAGE_UNAVAILABLE/);
assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM analytics_event WHERE client_event_id=?').get('WONT_COMMIT')!.n,0);
store.db.exec('DROP TRIGGER fail_insert');
store.db.prepare('DELETE FROM analytics_event WHERE client_event_id=?').run('A');
assert.deepEqual(run([A]).duplicated_event_ids,['A']);
assert.throws(()=>batch([{...A,client_event_id:''}]),/INVALID_BATCH/);
assert.throws(()=>batch([A], 'bad\nheader'),/INVALID_BATCH/);
store.close();
const reopened=new AnalyticsStore(join(dir,'analytics.db'));
assert.deepEqual(settleAnalyticsBatch(reopened,ctx,batch([B]),'after-restart').duplicated_event_ids,['B']);
reopened.close();rmSync(dir,{recursive:true,force:true});console.log('analytics ingest: PASS (exact ACK, transaction rollback, dedupe TTL/restart, safe receipts)');

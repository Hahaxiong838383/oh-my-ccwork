import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
const temp = mkdtempSync(join(tmpdir(), 'la-release-'));
for (const key of ['PROFILE','DEVICES','CONFIG','CONVERSATION','ACCOUNTS','FEEDBACK','DIAGNOSTICS','OTA','PAIRING','SMS','TELEMETRY']) process.env[`${key}_DB_PATH`] = join(temp, `${key}.db`);
process.env.LOCAL_AUDIO_DIR = join(temp, 'audio');
process.env.LOCAL_AUDIO_WRITES_PAUSED = '0';
const { localAudioStore: store, REQUIRED_SLOTS } = await import('../src/local-audio-store.js');
const { pcmToWav } = await import('../src/providers/xfyun-tts.js');
const { deviceRegistryStore } = await import('../src/device-registry-store.js');
const { relationStateStore } = await import('../src/relation-state-store.js');
const sn = 'BJP00326060100009981', acc = `device-${sn}`;
const db = new DatabaseSync(process.env.DEVICES_DB_PATH!);
db.prepare('INSERT INTO device_registry (sn,status,account_id,parent_account_id,created_at,updated_at) VALUES (?,?,?,?,?,?)').run(sn,'active',acc,'parent-test',1,1);
const profile = new DatabaseSync(process.env.PROFILE_DB_PATH!);
profile.exec('CREATE TABLE unrelated_test (id INTEGER PRIMARY KEY, value TEXT)');
profile.prepare('INSERT INTO unrelated_test VALUES (?, ?)').run(1, 'personality-must-stay');
const gen = { tier: '新朋友', traits: '{}' };
const audio = pcmToWav(Buffer.alloc(48000));
const keep = REQUIRED_SLOTS.flatMap(slot => [0,1].map(n => store.stageClipImmutable(acc, { slot, text: `短句${n}`, audio, durationMs: 1000, format:'wav' })).map(i=>({slot:i.slot,id:i.id})));
store.commitSet(acc, keep, gen, {expectedRevision:0});
// 只在临时数据库模拟已经存在的真实端侧回报；CLI任何操作不得动它。
store.recordFetch(acc,1,1);
const applied = { rev:store.getState(acc).last_applied_revision, at:store.getState(acc).last_applied_at, logs:store.listFetchLog(acc) };
const cli = (...args:string[]) => {
  const r=spawnSync(process.execPath,['--experimental-sqlite','--import','tsx',resolve('scripts/local-audio-release.ts'),...args],{encoding:'utf8',env:process.env});
  let result:any;try { result=JSON.parse(r.stdout.trim()); } catch { result={stdout:r.stdout,stderr:r.stderr}; }
  return {status:r.status,result};
};
const b1=join(temp,'bundle-old');
const beforeRows=profile.prepare('SELECT * FROM local_audio_item ORDER BY id').all();
const prepared=cli('prepare','--device-suffix','00009981','--output',b1);
assert.equal(prepared.status,0,JSON.stringify(prepared.result));
assert.equal(prepared.result.valid,true);
assert.deepEqual(profile.prepare('SELECT * FROM local_audio_item ORDER BY id').all(),beforeRows);
assert.equal(statSync(b1).mode&0o777,0o700);
assert.equal(statSync(join(b1,'bundle.json')).mode&0o777,0o600);
const verified=cli('verify','--bundle',b1);assert.equal(verified.status,0);
assert.equal(cli('verify','--bundle',b1,'--device-suffix','00009981').result.code,'invalid_arguments');
const bundleSha=prepared.result.bundle_sha256;
assert.equal(bundleSha,createHash('sha256').update(readFileSync(join(b1,'bundle.json'))).digest('hex'));
assert.equal(cli('publish','--bundle',b1,'--expect-revision','1','--expect-bundle-sha','0'.repeat(64)).result.code,'bundle_sha_mismatch');
process.env.LOCAL_AUDIO_WRITES_PAUSED='1';
assert.equal(cli('publish','--bundle',b1,'--expect-revision','1','--expect-bundle-sha',bundleSha).result.code,'local_audio_writes_paused');
process.env.LOCAL_AUDIO_WRITES_PAUSED='0';
db.prepare('UPDATE device_registry SET parent_account_id=? WHERE sn=?').run('other-parent',sn);
assert.equal(cli('publish','--bundle',b1,'--expect-revision','1','--expect-bundle-sha',bundleSha).result.code,'device_identity_changed');
db.prepare('UPDATE device_registry SET parent_account_id=? WHERE sn=?').run('parent-test',sn);
const relationBefore=profile.prepare('SELECT first_seen_at FROM relation_state WHERE account_id=?').get(acc);
relationStateStore.recordTurn(acc,{ts:777,sampleKey:'relation-change-test',valence:0,engagement:0.5});
profile.prepare('UPDATE relation_state SET first_seen_at=777 WHERE account_id=?').run(acc);
assert.equal(cli('publish','--bundle',b1,'--expect-revision','1','--expect-bundle-sha',bundleSha).result.code,'relation_identity_changed');
if (relationBefore) profile.prepare('UPDATE relation_state SET first_seen_at=? WHERE account_id=?').run(relationBefore.first_seen_at!,acc);
else profile.prepare('DELETE FROM relation_state WHERE account_id=?').run(acc);
const fixed=store.stageClipImmutable(acc,{slot:'device_reply.already',text:'现在就是这样啦',audio,durationMs:1000,format:'wav'});
store.commitSet(acc,[...keep,{slot:fixed.slot,id:fixed.id}],gen,{expectedRevision:1});
assert.equal(cli('publish','--bundle',b1,'--expect-revision','1','--expect-bundle-sha',bundleSha).result.code,'revision_conflict');
assert.equal(store.getState(acc).revision,2);
const recovered=cli('recover','--bundle',b1,'--expect-revision','2','--expect-bundle-sha',bundleSha);
assert.equal(recovered.status,0,JSON.stringify(recovered.result));assert.equal(recovered.result.revision,3);
assert.deepEqual(store.listActive(acc).map(i=>i.id).sort(),keep.map(i=>i.id).sort());
assert.deepEqual({rev:store.getState(acc).last_applied_revision,at:store.getState(acc).last_applied_at,logs:store.listFetchLog(acc)},applied);
assert.equal(profile.prepare('SELECT value FROM unrelated_test').get()!.value,'personality-must-stay');
// 即使篡改bundle摘要重新获授权，缺槽也不能进库。
const doc=JSON.parse(readFileSync(join(b1,'bundle.json'),'utf8'));doc.items.shift();
writeFileSync(join(b1,'bundle.json'),JSON.stringify(doc));
assert.equal(cli('verify','--bundle',b1).result.code,'invalid_slot_count');
const invalidSha=createHash('sha256').update(readFileSync(join(b1,'bundle.json'))).digest('hex');
assert.equal(cli('publish','--bundle',b1,'--expect-revision','3','--expect-bundle-sha',invalidSha).result.code,'invalid_slot_count');
assert.equal(store.getState(acc).revision,3);
console.log('local-audio-release: readonly preparation / permissions / bundle authorization / identity / CAS / forward recovery / keep applied + unrelated data PASS');

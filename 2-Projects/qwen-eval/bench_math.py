SYSTEM = "你是一个数学老师。请解答以下数学题，在最后一行用 '答案：数字' 的格式给出最终数字答案。只输出数字，不要单位。"


def extract_answer(text):
    """Extract numeric answer from response."""
    # look for 答案：N or 答案: N
    m = re.search(r'答案[：:]\s*([-\d.]+)', text)
    if m:
        return float(m.group(1))
    # fallback: last number in text
    nums = re.findall(r'[-\d.]+', text)
    if nums:
        return float(nums[-1])
    return None


def run(config=None):
    config = config or load_config()
    client = get_client(config)
    model = config["api"]["model"]

    print_header("Math Reasoning (GSM8K-style)")
    correct = 0
    total = len(PROBLEMS)

    for i, p in enumerate(PROBLEMS):
        resp = chat(client, model, [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": p["q"]},
        ], max_tokens=300, temperature=0.0)

        pred = extract_answer(resp)
        expected = p["a"]
        ok = pred is not None and abs(pred - expected) < 0.01
        if ok:
            correct += 1
        status = "✓" if ok else "✗"
        print(f"  [{status}] Q{i+1}: expected={expected}, got={pred}")

    accuracy = correct / total * 100
    print(f"\n  Score: {correct}/{total} = {accuracy:.1f}%")
    return {"correct": correct, "total": total, "accuracy": round(accuracy, 1)}


